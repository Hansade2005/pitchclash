// Builds goal-nation's public/js/real_squads.js from Pitch Clash's REAL_SQUADS.
// Usage: node tools/gn_squads.mjs <goal-nation-checkout>
import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';
import { CLUBS as MAIN_CLUBS } from '../src/data/teams.js';
import { REAL_SQUADS } from '../src/data/real_squads.js';

const root = process.argv[2];
const tmp = path.join(root, 'public/js/.data_tmp.mjs');
fs.copyFileSync(path.join(root, 'public/js/data.js'), tmp);
const gn = await import(pathToFileURL(tmp).href);
fs.unlinkSync(tmp);

const mainByName = new Map(MAIN_CLUBS.map((c) => [c.name, c.id]));
// slot order in goal-nation: GK, 4 DF, 4 MF, 2 FW, then 5 subs. Real lists usually start with 3 keepers,
// so use the first keeper as the starter, outfield names next, and the other keepers on the bench.
const order = (l) => (l.length >= 6 ? [l[0], ...l.slice(3), l[1], l[2]] : l).slice(0, 16);
const out = {};
for (const t of [...gn.TEAMS, ...gn.CLUBS]) {
  const mid = t.club ? mainByName.get(t.name) : t.id;
  const list = mid && REAL_SQUADS[mid];
  if (list && list.length) out[t.id] = order(list);
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
fs.writeFileSync(path.join(root, 'public/js/real_squads.js'), `// Real player names by team id (generated by tools/gn_squads.mjs from Pitch Clash research).\n// Teams not listed use generated names. Names fill squad slots in order.\nexport const REAL = {\n${body}\n};\n`);
console.log('teams with real names:', Object.keys(out).length, 'of', gn.TEAMS.length + gn.CLUBS.length);
